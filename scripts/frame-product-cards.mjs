import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

// Framing trims surrounding wall/white space. Every photograph remains the
// original capture; the stone, proportions and existing marks are preserved.
const app = resolve('artifacts/stoneworks');
const inventory = JSON.parse(await readFile(resolve(app, 'output/product-card-audit/photo-inventory.json'), 'utf8'));
const viewports = {
  'copper-vein-basin': [0, 130, 640, 400],
  'vessel-sink': [40, 65, 670, 365],
  'coaster-suite': [0, 90, 600, 620],
  'travertine-bath-seven': [0, 0, 736, 690],
  'travertine-compote': [0, 240, 736, 625],
  'portoro-bookends': [0, 170, 736, 566],
};
await mkdir(resolve(app, 'public/gallery/card-frames'), { recursive: true });
const metadata = {};
const report = [];
for (const photo of inventory) {
  const frame = viewports[photo.slug];
  const [width, height] = photo.size;
  let src = photo.src;
  let displayWidth = width;
  let displayHeight = height;
  if (frame) {
    const bytes = await readFile(resolve(app, 'public' + photo.src));
    src = '/gallery/card-frames/' + photo.slug + '.svg';
    const [x, y, w, h] = frame;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${x} ${y} ${w} ${h}" overflow="hidden"><image width="${width}" height="${height}" href="data:image/jpeg;base64,${bytes.toString('base64')}"/></svg>\n`;
    await writeFile(resolve(app, 'public' + src), svg);
    displayWidth = w;
    displayHeight = h;
    report.push({ slug: photo.slug, source: photo.src, src, viewport: frame, sourceSha256: createHash('sha256').update(bytes).digest('hex'), pixelEdits: false });
  }
  metadata[photo.src] = { src, width: displayWidth, height: displayHeight, ...(photo.slug === 'travertine-bath' ? { native: true } : {}) };
}
await writeFile(resolve(app, 'src/data/catalogue-photos.ts'), `// Actual display dimensions and source-preserving card viewports.\n// Generated by scripts/frame-product-cards.mjs from the audited catalogue.\nexport type CataloguePhoto = { src: string; width: number; height: number; native?: boolean };\n\nexport const cataloguePhotos: Record<string, CataloguePhoto> = ${JSON.stringify(metadata, null, 2)};\n`);
await mkdir(resolve('output/product-card-audit'), { recursive: true });
await writeFile(resolve('output/product-card-audit/framing.json'), JSON.stringify(report, null, 2));
console.log(`Prepared ${inventory.length} photo records and ${report.length} original-photo viewports.`);
