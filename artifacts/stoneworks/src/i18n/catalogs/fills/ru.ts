/** Russian plural: 1 работа, 2–4 работы, 5+ работ. */
const works = (count: number): string => {
  const n = Math.abs(count) % 100;
  const n1 = n % 10;
  if (n > 10 && n < 20) return 'работ';
  if (n1 === 1) return 'работа';
  if (n1 >= 2 && n1 <= 4) return 'работы';
  return 'работ';
};

/** Russian plural for «коллекция»; `accusative` gives 1 коллекцию. */
const collections = (count: number, accusative = false): string => {
  const n = Math.abs(count) % 100;
  const n1 = n % 10;
  if (n > 10 && n < 20) return 'коллекций';
  if (n1 === 1) return accusative ? 'коллекцию' : 'коллекция';
  if (n1 >= 2 && n1 <= 4) return 'коллекции';
  return 'коллекций';
};

