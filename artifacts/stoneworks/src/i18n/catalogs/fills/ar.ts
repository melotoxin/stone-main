import type { PartialCatalog } from '../fallback';

type ArCountForms = { one: string; two: string; few: string; many: string; hundred?: string };

/**
 * Arabic number agreement: 1 and 2 use the singular + واحد / the dual without a
 * numeral, 3–10 take the plural, 11–99 the singular (tamyīz), and round
 * hundreds the singular genitive. `count` may be a zero-padded string ("05").
 */
export const arCount = (count: number | string, forms: ArCountForms): string => {
  const n = Number(count);
  if (!Number.isFinite(n)) return `${count} ${forms.few}`;
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  const rest = n % 100;
  if (rest >= 3 && rest <= 10) return `${count} ${forms.few}`;
  if (rest >= 11) return `${count} ${forms.many}`;
  return n === 0 ? `${count} ${forms.few}` : `${count} ${forms.hundred ?? forms.many}`;
};

